package BasicsOfJava;

public class doubledatatype {
    public static void main(String[] args) {
        int x = 5;
        int y = 2;
        int z = x / y;
        System.out.println(z);

        double a = 5;
        double b = 2;
        double c = a / b;
        System.out.println(c);

        double d = 5.0 / 2;
        System.out.println(d);

    }
}
